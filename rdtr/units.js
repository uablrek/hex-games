// Prerequisite: main.sc is defined
export async function init() {
	// Define .stat from .s and .m
	for (const u of units) {
		if ('s' in u)
			u.stat = u.m ? `${u.s}-${u.m}` : `${u.s}`
	}
	unit.addUnitGenerator('nav', unit.ugenNav)
    unit.addUnitGenerator('ab', unit.ugenAb)
	unit.addUnitGenerator('bh', ugenBh)
	await unit.init(units, nations, 0.88)
	// Mark initial-deployment units
	for (const au of sc.initialDeployment) {
		for (let i = 0; i < au.cnt; i++) {
			const u = unit.fromStr(au.type, (u)=>u.selected)
			u.initial = true
			u.allowable = true
		}
	}	
	// Mark allowable units
	for (const au of sc.allowableBuilds[0].units) {
		for (let i = 0; i < au.cnt; i++) {
			const u = unit.fromStr(au.type, (u)=>u.selected)
			u.allowable = true
		}
	}
	for (const u of units)
		if (u.type == "ab") u.initial = u.allowable = true
	unit.unselectAll()
}
function ugenBh(conf, u, side) {
	u.add(new Konva.Circle({
		stroke: conf.stroke,
		radius: side*0.33,
		strokeWidth: 3,
		x: side/2,
		y: side/2,
	}))
	u.add(new Konva.Text({
		fill: conf.stroke,
		text: "BH",
		fontStyle: 'bold',
		fontFamily: 'sans-serif',
		fontSize: side/3,
		x: side*0.26,
		y: side*0.32,
	}))
	return true
}

