export function deploy(nat, filterOut, hex) {
	const unitbox = new unit.UnitBox(unitBoxConf[nat].conf)
	if (!filterOut) filterOut = (u)=>false
	for (const u of units) {
		if (u.hex) continue
		if (u.nat != nat) continue
		if (filterOut(u)) continue 
		unitbox.addUnit(u)
	}
	if (!hex) hex = unitBoxConf[nat].hex
	unitbox.box.position(grid.hexToPixel(hex))
	ui.board.add(unitbox.box)
	// We want the unitbox to be visible, so the board is scrolled.
	center(hex)
	return unitbox
}

export function isMinorAlly(nat) {
	return ["fi","ru","hu","bu"].includes(nat)
}
export function isMajor(nat) {
	return ["ge","it","uk","fr","su","us"].includes(nat)
}
let splitBox
function openSplitBox() {
	// this = main.selected
	const u = this.u
	if (splitBox) return
	if (!u) return
	if (u.type != "air" && u.type != "nav") return
	if (!isMajor(u.nat)) return
	splitBox = new unit.UnitBox(splitBoxConf[u.type])
	const pos = grid.hexToPixel(u.hex)
	splitBox.box.position({x:pos.x - 50, y:pos.y - 200})
	splitBox.destroyCallback = function(){splitBox = null}
	ui.board.add(splitBox.box)
}
export function enableSplitBox() {
	selected.fn = openSplitBox.bind(selected)
}
export function disableSplitbox() {
	selected.fn = null
	if (splitBox) splitBox.destroy()
	splitBox = null
}

